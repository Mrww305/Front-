import express from 'express';
import { fileURLToPath } from 'url';
import { dirname, join } from 'path';
import fs from 'fs';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

const app = express();
const PORT = process.env.PORT || 3000;
const HOST = process.env.HOST || '0.0.0.0';

app.use(express.json());

// API health endpoint for uptime checks & deployment verification
app.get('/api/health', (req, res) => {
  res.json({
    status: 'ok',
    uptime: Math.floor(process.uptime()),
    timestamp: new Date().toISOString(),
    service: 'megnitoo-experience-studio',
  });
});

// Serve static assets generated by Vite build
const distPath = join(__dirname, 'dist');
app.use(express.static(distPath));

// Fallback to index.html for client-side SPA routing
app.get('*', (req, res) => {
  const indexPath = join(distPath, 'index.html');
  if (fs.existsSync(indexPath)) {
    res.sendFile(indexPath);
  } else {
    res.status(200).send(`
      <!DOCTYPE html>
      <html lang="en">
        <head>
          <meta charset="UTF-8">
          <meta name="viewport" content="width=device-width, initial-scale=1.0">
          <title>MEGNITOO Experience Studio</title>
          <style>
            body {
              margin: 0;
              background-color: #050508;
              color: #f1f5f9;
              font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif;
              display: flex;
              align-items: center;
              justify-content: center;
              min-height: 100vh;
              text-align: center;
              padding: 24px;
            }
            .card {
              max-width: 500px;
              background: rgba(255, 255, 255, 0.03);
              border: 1px solid rgba(255, 255, 255, 0.1);
              border-radius: 16px;
              padding: 32px;
            }
            h1 { font-size: 1.5rem; margin-bottom: 8px; color: #8b5cf6; }
            p { font-size: 0.95rem; color: #94a3b8; line-height: 1.6; }
            code { background: rgba(255,255,255,0.1); padding: 3px 6px; border-radius: 4px; font-size: 0.85rem; color: #38bdf8; }
          </style>
        </head>
        <body>
          <div class="card">
            <h1>MEGNITOO Server Ready</h1>
            <p>Node.js / Express server is online on port ${PORT}. If client assets have not been compiled yet, please run <code>npm run build</code>.</p>
          </div>
        </body>
      </html>
    `);
  }
});

app.listen(Number(PORT), HOST, () => {
  console.log(`MEGNITOO production server running on http://${HOST}:${PORT}`);
});
